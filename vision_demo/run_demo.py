"""Run the reproducible synthetic camera and visual-control demo."""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

import cv2

from .controller import compute_command
from .detector import annotate_frame, detect_orange_target
from .synthetic_scene import SceneConfig, render_frame, target_position


def run_demo(output_dir: Path, frames: int = 120, fps: int = 20) -> dict[str, object]:
    output_dir.mkdir(parents=True, exist_ok=True)
    config = SceneConfig()
    video_path = output_dir / "vision_tracking_demo.mp4"
    csv_path = output_dir / "tracking_log.csv"
    summary_path = output_dir / "summary.json"

    writer = cv2.VideoWriter(
        str(video_path),
        cv2.VideoWriter_fourcc(*"mp4v"),
        fps,
        (config.width, config.height),
    )
    if not writer.isOpened():
        raise RuntimeError("Could not open MP4 writer; check the local OpenCV codec setup")

    detected = 0
    errors: list[float] = []
    rows: list[dict[str, object]] = []

    try:
        for frame_index in range(frames):
            frame = render_frame(frame_index, config)
            detection, _ = detect_orange_target(frame)
            command = compute_command(detection)
            annotated = annotate_frame(frame, detection, command, config.width // 2)
            writer.write(annotated)

            expected_x, expected_y = target_position(frame_index, config)
            if detection is not None:
                detected += 1
                errors.append(((detection.center_x - expected_x) ** 2 + (detection.center_y - expected_y) ** 2) ** 0.5)

            rows.append(
                {
                    "frame": frame_index,
                    "expected_x": expected_x,
                    "expected_y": expected_y,
                    "detected": detection is not None,
                    "detected_x": detection.center_x if detection else "",
                    "detected_y": detection.center_y if detection else "",
                    "target_area": round(detection.area, 2) if detection else "",
                    "linear_x": round(command[0], 5),
                    "angular_z": round(command[1], 5),
                }
            )
    finally:
        writer.release()

    with csv_path.open("w", newline="", encoding="utf-8") as handle:
        fieldnames = list(rows[0])
        writer_csv = csv.DictWriter(handle, fieldnames=fieldnames)
        writer_csv.writeheader()
        writer_csv.writerows(rows)

    summary = {
        "frames": frames,
        "detected_frames": detected,
        "detection_rate": detected / frames,
        "mean_pixel_error": sum(errors) / len(errors) if errors else None,
        "data_source": "synthetic camera frames generated by this repository",
        "method": "HSV thresholding + morphology + largest contour",
        "controller": "bounded proportional image-error and target-area control",
        "video": str(video_path.name),
        "log": str(csv_path.name),
    }
    summary_path.write_text(json.dumps(summary, indent=2), encoding="utf-8")
    return summary


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=Path("results"))
    parser.add_argument("--frames", type=int, default=120)
    parser.add_argument("--fps", type=int, default=20)
    args = parser.parse_args()
    summary = run_demo(args.output_dir, frames=args.frames, fps=args.fps)
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()

